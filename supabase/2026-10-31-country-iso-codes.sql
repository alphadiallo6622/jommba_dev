-- Reprise de donnees : profiles.country passe du nom de pays au code ISO.
--
-- Avant : la colonne avait pour defaut 'SN', si bien que tout compte cree
-- sans renseigner sa localisation etait marque Senegal sans jamais l avoir
-- choisi. Les membres ayant reellement rempli l etape 5/7 stockaient, eux, le
-- nom francais du pays ('Guinee', 'France'...). On unifie sur le code ISO.

-- 0) Sauvegarde : permet de revenir en arriere.
create table if not exists public.profiles_country_backup_20261031 as
select user_id, city, country, now() as backed_up_at from public.profiles;

-- 1) Les profils restes sur le defaut 'SN' n ont jamais choisi de pays
--    (leur ville est vide) : ils basculent en Guinee. A faire AVANT l etape 2,
--    car apres conversion le vrai Senegal porte lui aussi le code 'SN'.
update public.profiles
set    country = 'GN'
where  country is null or country = 'SN';

